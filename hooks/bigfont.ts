export const GLYPH_W = 5

/** Uppercases, drops accents, and keeps only characters the font has. */
export const printable = (text: string) =>
  text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .split('')
    .map(c => (GLYPHS[c] ? c : '-'))
    .join('')

/**
 * The text as 4 rows of half blocks, one string per glyph per row:
 * rows[r][i] is glyph i's slice of row r, GLYPH_W columns wide.
 */
export const bigRows = (text: string): string[][] => {
  const glyphs = printable(text).split('').map(c => (GLYPHS[c] ?? GLYPHS[' '] ?? '').split(' '))
  const on = (g: string[], x: number, y: number) => g[y]?.[x] === '#'
  const rows: string[][] = [[], [], [], []]
  for (let r = 0; r < 4; r++) {
    for (const g of glyphs) {
      let cell = ''
      for (let x = 0; x < GLYPH_W; x++) {
        const top = on(g, x, r * 2)
        const bottom = on(g, x, r * 2 + 1)
        cell += top && bottom ? '█' : top ? '▀' : bottom ? '▄' : ' '
      }
      rows[r]?.push(cell)
    }
  }
  return rows
}

/** A hex color between `a` and `b`, at t in 0..1. */
export const mix = (a: string, b: string, t: number) => {
  const pa = [1, 3, 5].map(i => parseInt(a.slice(i, i + 2), 16))
  const pb = [1, 3, 5].map(i => parseInt(b.slice(i, i + 2), 16))
  return `#${pa
    .map((v, i) => Math.round(v + ((pb[i] ?? v) - v) * t).toString(16).padStart(2, '0'))
    .join('')}`
}
